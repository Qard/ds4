#!/usr/bin/env python3
"""Regenerate ds4_qwen4_unicode.inc, the codepoint classes of the Qwen3.8
("qwen35") pre-tokenizer regex, from the `regex` module's Unicode tables.
Use a current `regex` release; the generated header records its version.
With --muse, use tokenizers==0.23.3 to match the checkpoint regex engine
(the Python regex module has different Unicode tables).

Usage: python gen_qwen4_unicode.py > ../ds4_qwen4_unicode.inc
"""
import argparse
import sys

import regex

CLASSES = {
    "letter": r"\p{L}",
    "mark": r"\p{M}",
    "number": r"\p{N}",
    "space": r"\s",
}


def tokenizer_ranges(cls):
    # Removed matches leave their complement with Unicode scalar offsets.
    # Separate the surrogate gap so every emitted range contains valid scalars.
    from tokenizers import Regex
    from tokenizers.pre_tokenizers import Split
    split = Split(Regex('(?:' + cls + ')+'), 'removed')
    ranges = []
    for first, end in ((0, 0xD800), (0xE000, 0x110000)):
        text = ''.join(map(chr, range(first, end)))
        pos = 0
        for _, (lo, hi) in split.pre_tokenize_str(text):
            if lo > pos:
                ranges.append((first + pos, first + lo - 1))
            pos = hi
        if pos < len(text):
            ranges.append((first + pos, end - 1))
    return ranges


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--muse', action='store_true', help='Emit GPT-4o case classes for Muse')
    args = parser.parse_args()
    if args.muse:
        classes = {**CLASSES, 'upper': r'[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]',
                   'lower': r'[\p{Ll}\p{Lm}\p{Lo}\p{M}]'}
        prefix = 'ds4_muse'
    else:
        classes, prefix = CLASSES, 'ds4_qwen4'
    out = sys.stdout
    if args.muse:
        import tokenizers
        out.write("/* Generated by gguf-tools/gen_qwen4_unicode.py --muse using\n")
        out.write(f" * Hugging Face tokenizers {tokenizers.__version__}, the checkpoint's regex engine. */\n\n")
    else:
        out.write("/* Generated by gguf-tools/gen_qwen4_unicode.py from the `regex` module's\n")
        out.write(f" * Unicode tables (regex {regex.__version__}); codepoint classes for the\n")
        out.write(" * Qwen3.8 pre-tokenizer. */\n\n")
    if not args.muse:
        out.write("typedef struct { uint32_t lo, hi; } ds4_qwen4_urange;\n\n")
    for index, (name, cls) in enumerate(classes.items()):
        if index:
            out.write("\n")
        if args.muse:
            ranges = tokenizer_ranges(cls)
        else:
            pat = regex.compile(cls, regex.V1)
            ranges = []
            lo = prev = None
            for cp in range(0x110000):
                m = False if 0xD800 <= cp <= 0xDFFF else pat.match(chr(cp)) is not None
                if m:
                    if lo is None:
                        lo = cp
                    prev = cp
                elif lo is not None:
                    ranges.append((lo, prev))
                    lo = None
            if lo is not None:
                ranges.append((lo, prev))
        out.write(f"static const ds4_qwen4_urange {prefix}_{name}_ranges[] = {{\n")
        for i in range(0, len(ranges), 4):
            out.write("    " + " ".join(f"{{0x{a:05x}, 0x{b:05x}}}," for a, b in ranges[i:i + 4]) + "\n")
        out.write("};\n")


if __name__ == "__main__":
    main()
